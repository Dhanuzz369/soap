// npm run consent:zones
//
// Writes src/lib/consent-timezones.ts: every time zone of the countries in src/lib/consent-regions.ts,
// so the browser can tell (from Intl's time zone, with no request) whether to ask before analytics.
// Each zone is listed under its IANA name and under the older name browsers may report for it
// (Chrome says Asia/Saigon, not Asia/Ho_Chi_Minh). Europe/* zones are left out: the site asks for
// every one of them anyway. Source: the system's tz database (zone.tab). Run it after changing the
// country list, and when a new tz release adds zones.
import { readFileSync, writeFileSync } from 'node:fs';
import { CONSENT_COUNTRIES } from '../src/lib/consent-regions.ts';

const TAB = process.env.ZONE_TAB ?? '/usr/share/zoneinfo/zone.tab';
const wanted = new Set(CONSENT_COUNTRIES);
const rows = readFileSync(TAB, 'utf8')
  .split('\n')
  .filter((l) => l && !l.startsWith('#'))
  .map((l) => l.split('\t'));

const zones = new Set();
const seen = new Set();
for (const [cc, , zone] of rows) {
  if (!wanted.has(cc)) continue;
  seen.add(cc);
  let alias = zone;
  try {
    alias = new Intl.DateTimeFormat('en', { timeZone: zone }).resolvedOptions().timeZone;
  } catch {
    /* a zone newer than Node's own tz data: its IANA name is enough */
  }
  for (const name of [zone, alias]) {
    if (!name.startsWith('Europe/')) zones.add(name);
  }
}
// Countries the tz database has no zone of its own for are covered by Google's region check alone.
const missing = CONSENT_COUNTRIES.filter((c) => !seen.has(c));
if (missing.length) console.warn(`[consent:zones] no zone in ${TAB} for: ${missing.join(', ')}`);

const list = [...zones].sort();
writeFileSync(
  new URL('../src/lib/consent-timezones.ts', import.meta.url),
  `// Generated by \`npm run consent:zones\` (scripts/consent-timezones.mjs) from the tz database. Do not edit.\n` +
    `// Time zones (other than Europe/*) of the countries in src/lib/consent-regions.ts.\n` +
    `export const CONSENT_TIMEZONES: readonly string[] = ${JSON.stringify(list, null, 2).replace(/"/g, "'")};\n`,
);
console.log(`[consent:zones] ${list.length} time zones for ${seen.size} countries`);
